#!/usr/bin/env python3
"""Build independent headless and Web packages against the fixed host baseline."""
import argparse,fcntl,hashlib,subprocess,sys
from pathlib import Path
root=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser();parser.add_argument('--headless',action='store_true');parser.add_argument('--configuration',choices=['debug','release'],default='debug');args=parser.parse_args()
(root/'.build').mkdir(exist_ok=True)
# The generated peer pin is shared by configurations; reject competing build wrappers.
pairing_lock=(root/'.build/host-pairing.lock').open('a+')
try:fcntl.flock(pairing_lock,fcntl.LOCK_EX|fcntl.LOCK_NB)
except BlockingIOError:raise SystemExit('Another paired build is active; retry after it completes.')
version=subprocess.check_output(['swift','--version'],text=True)
if '6.4.1' not in version:raise SystemExit('Swift 6.4.1 is required by toolchain.lock.json')
def run(directory,*command,timeout=900):subprocess.run([sys.executable,str(root/'Tools/run.py'),str(timeout),*command],cwd=directory,check=True)
run(root,'swift','build','-c',args.configuration,'--product','architecture')
if not args.headless:run(root/'Apps/ArchitectureExplorerWeb','swift','build','--build-system','native','-Xswiftc','-target','-Xswiftc','arm64-apple-macosx27.0','-c',args.configuration,'--product','architecture-web')

if not args.headless:
 helper=root/'Apps/ArchitectureExplorerWeb/.build'/args.configuration/'architecture-web'
 digest=hashlib.sha256(helper.read_bytes()).hexdigest()
 generated=root/'Sources/architecture/Commands/HostBuildIdentity.generated.swift'
 generated.write_text('// Generated by Tools/build.py. Do not edit.\nenum HostBuildIdentity { static let webDigest = "'+digest+'" }\n')
 run(root,'swift','build','-c',args.configuration,'--product','architecture','-Xswiftc','-DARCHITECTURE_PAIRED_WEB')
